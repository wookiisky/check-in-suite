import { expect, test } from '@playwright/test';
import content from '../src/content/zh-CN.json' with { type: 'json' };
import family from '../src/features/family/content.json' with { type: 'json' };
import shop from '../src/features/shop/content.json' with { type: 'json' };

test('首页形象入口更新角色并保留留言，背包与商店使用多级分类', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await page.getByLabel(content.account.username).fill('island-e2e');
  await page.getByLabel(content.account.loginPassword).fill('Island-Test-2026');
  await page.getByRole('button', { name: content.account.login, exact: true }).click();
  const message = page.getByLabel(family.input, { exact: true });
  await message.fill('换装时保留的家庭留言草稿');
  const opener = page.getByRole('button', { name: shop.wardrobeTitle, exact: true });
  await opener.click();
  const wardrobe = page.getByRole('dialog', { name: shop.wardrobeTitle, exact: true });
  await expect(wardrobe).toBeVisible();
  const girl = wardrobe.getByRole('button', { name: shop.baseAvatarNames['avatar-girl-v2'], exact: true });
  await expect(girl).toBeVisible();
  await wardrobe.screenshot({ path: `.local/previews/wardrobe-dialog-${testInfo.project.name}.png` });
  await girl.click();
  await expect(girl).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('Escape');
  await expect(wardrobe).toHaveCount(0);
  await expect(opener).toBeFocused();
  await expect(message).toHaveValue('换装时保留的家庭留言草稿');
  await expect(page.locator('.camp-character-panel > .shop-character [data-base-avatar]')).toHaveAttribute('data-base-avatar', 'avatar-girl-v2');
  await page.locator('.camp-character-panel').screenshot({ path: `.local/previews/home-character-${testInfo.project.name}.png` });
  await page.getByRole('button', { name: shop.backpack, exact: true }).click();
  await expect(page.getByRole('heading', { name: shop.backpack, exact: true })).toBeVisible();
  await expect(page.getByText(shop.loading, { exact: true })).toHaveCount(0);
  await page.getByRole('heading', { name: shop.backpack, exact: true }).evaluate((heading) => heading.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: `.local/previews/backpack-${testInfo.project.name}.png` });
  const groups = page.getByRole('tablist', { name: shop.categoryGroupLabel, exact: true });
  await groups.getByRole('tab', { name: shop.categoryGroups.appearance, exact: true }).click();
  const details = page.getByRole('tablist', { name: shop.categoryDetailLabel, exact: true });
  await details.getByRole('tab', { name: shop.wearableSlots.hair, exact: true }).click();
  await page.getByRole('button', { name: shop.wardrobeTitle, exact: true }).click();
  await expect(wardrobe).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(details.getByRole('tab', { name: shop.wearableSlots.hair, exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('button', { name: shop.wardrobeTitle, exact: true })).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: content.navigation.shop, exact: true }).click();
  await groups.getByRole('tab', { name: shop.categoryGroups.appearance, exact: true }).click();
  await details.getByRole('tab', { name: shop.wearableSlots.hair, exact: true }).click();
  await details.getByRole('tab', { name: shop.wearableSlots.hair, exact: true }).press('ArrowRight');
  await expect(details.getByRole('tab', { name: shop.wearableSlots.top, exact: true })).toBeFocused();
  await expect(details.getByRole('tab', { name: shop.wearableSlots.top, exact: true })).toHaveAttribute('aria-selected', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const selectedCategory = details.getByRole('tab', { name: shop.allTypes, exact: true });
  await selectedCategory.click();
  await selectedCategory.hover();
  const selectedBackground = await selectedCategory.evaluate((tab) => {
    const swatch = document.createElement('span');
    swatch.style.backgroundColor = 'var(--forest)';
    tab.append(swatch);
    const color = getComputedStyle(swatch).backgroundColor;
    swatch.remove();
    return color;
  });
  await expect(selectedCategory).toHaveCSS('background-color', selectedBackground);
  await expect(page.getByText(shop.loading, { exact: true })).toHaveCount(0);
  await expect(page.getByRole('article').first()).toBeVisible();
  await page.screenshot({ path: `.local/previews/shop-tabs-${testInfo.project.name}.png`, fullPage: true });
});
