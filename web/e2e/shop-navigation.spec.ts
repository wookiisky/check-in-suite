import { expect, test } from '@playwright/test';
import content from '../src/content/zh-CN.json' with { type: 'json' };
import family from '../src/features/family/content.json' with { type: 'json' };
import shop from '../src/features/shop/content.json' with { type: 'json' };
import appearance from '../src/features/shop/appearance-content.json' with { type: 'json' };
import { loginMain, openBackpack } from './shop-navigation';

// 弹窗保留焦点及首页输入，商店与背包各自保存两级分类。
test('三维形象入口保留留言和焦点，背包及商店分类支持键盘', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await loginMain(page);
  const message = page.getByLabel(family.input, { exact: true });
  await message.fill('关闭外观后仍保留的留言草稿');
  const opener = page.getByRole('button', { name: shop.wardrobeTitle, exact: true });
  await opener.click();
  const dialog = page.getByRole('dialog', { name: appearance.title, exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('group', { name: appearance.slots.head, exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: appearance.cancel, exact: true }).click();
  await expect(opener).toBeFocused();
  await expect(message).toHaveValue('关闭外观后仍保留的留言草稿');
  await message.fill('');
  await openBackpack(page);
  const groups = page.getByRole('tablist', { name: shop.categoryGroupLabel, exact: true });
  const details = page.getByRole('tablist', { name: shop.categoryDetailLabel, exact: true });
  await groups.getByRole('tab', { name: shop.categoryGroups.appearance, exact: true }).click();
  await details.getByRole('tab', { name: shop.wearableSlots.head, exact: true }).click();
  const backpackOpener = page.getByRole('button', { name: shop.wardrobeTitle, exact: true });
  await backpackOpener.click();
  await dialog.getByRole('button', { name: appearance.cancel, exact: true }).click();
  await expect(backpackOpener).toBeFocused();
  await expect(details.getByRole('tab', { name: shop.wearableSlots.head, exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: content.navigation.shop, exact: true }).click();
  await groups.getByRole('tab', { name: shop.categoryGroups.appearance, exact: true }).click();
  await details.getByRole('tab', { name: shop.wearableSlots.head, exact: true }).click();
  await details.getByRole('tab', { name: shop.wearableSlots.head, exact: true }).press('ArrowRight');
  await expect(details.getByRole('tab', { name: shop.wearableSlots.upper, exact: true })).toBeFocused();
  await expect(details.getByRole('tab', { name: shop.wearableSlots.upper, exact: true })).toHaveAttribute('aria-selected', 'true');
  await details.getByRole('tab', { name: shop.allTypes, exact: true }).click();
  await expect(page.getByRole('article').first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
